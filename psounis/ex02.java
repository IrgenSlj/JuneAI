class ex02 {
    public static void main(String[] args) {
        double d = 3.23;
        System.out.println(d);

        long l = 147L;
        System.out.println(l);

        boolean b = false;
        System.out.println(b);

        double du = 45E0;
        System.out.println(du);

        int i =  0XA1;
        System.out.println(i);

        char c = '\u0041';
        System.out.println(c);
    }
}